#!/usr/bin/env bash

set -euo pipefail

repo_root="${1:-.}"
module_path="$(awk '/^module / { print $2; exit }' "${repo_root}/go.mod")"
if [[ -z "${module_path}" ]]; then
  echo "failed to read module path from ${repo_root}/go.mod" >&2
  exit 1
fi

output="${repo_root}/internal/debugger/registry/registry.go"
mkdir -p "$(dirname "${output}")"
tmp_file="$(mktemp)"
trap 'rm -f "${tmp_file}"' EXIT

{
  echo '// Code generated by scripts/generate_debugger_registry.sh; DO NOT EDIT.'
  echo
  echo 'package registry'
  echo
  echo 'import ('
  (
    cd "${repo_root}"
    find . -type f -name 'services_grpc.pb.go' ! -path './.git/*' ! -path './upstream/*' -print \
      | LC_ALL=C sort \
      | sed 's|^\./||; s|/services_grpc.pb.go$||' \
      | sed "s|^|\\t_ \"${module_path}/|" \
      | sed 's|$|"|'
  )
  echo ')'
} > "${tmp_file}"

if [[ ! -f "${output}" ]] || ! cmp -s "${tmp_file}" "${output}"; then
  mv "${tmp_file}" "${output}"
else
  rm -f "${tmp_file}"
fi

echo "generated debugger registry: ${output}"
